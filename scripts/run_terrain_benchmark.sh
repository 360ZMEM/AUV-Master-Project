#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════
# 地形跟随基准测试 - PID/MPC × CONSTANT/TERRAIN_FOLLOWING
#
# 用法:
#   bash scripts/run_terrain_benchmark.sh [DURATION_SECONDS] [pid|mpc|both] [baseline|terrain|both_modes] [default|low|mid|high|<bridge_cfg.yaml>]
#
# 输出:
#   results/control/terrain_following_<timestamp>/
#     ├── pid_baseline/
#     ├── pid_terrain/
#     ├── mpc_baseline/
#     └── mpc_terrain/
# ═══════════════════════════════════════════════════════════════════
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SCRIPTS_DIR="$ROOT_DIR/scripts"
BRAIN_CONFIG_DIR="$ROOT_DIR/brain_linux/config"
DEFAULT_TERRAIN_BRIDGE_CFG="$ROOT_DIR/config/bridge_params.protocol_udp.pvs.terrain.yaml"
TERRAIN_BRIDGE_CFG="${TERRAIN_BRIDGE_CFG:-}"
FEATURE_FLAGS="$BRAIN_CONFIG_DIR/feature_flags.yaml"
FEATURE_FLAGS_BACKUP="$BRAIN_CONFIG_DIR/.feature_flags_backup.yaml"

DATA_ROOT=$(python3 -c "import sys; sys.path.append('$ROOT_DIR'); from common.env_utils import get_data_root; print(get_data_root())")
LOG_ROOT="${AUV_EXPERIMENT_LOG_ROOT:-$DATA_ROOT/bags}"
AUV_WARMUP_SKIP_S="${AUV_WARMUP_SKIP_S:-10}"
AUV_TERRAIN_ENABLE_BEHAVIOR_TREE="${AUV_TERRAIN_ENABLE_BEHAVIOR_TREE:-true}"
AUV_TERRAIN_BYPASS_TO_MANUAL_SETPOINT="${AUV_TERRAIN_BYPASS_TO_MANUAL_SETPOINT:-false}"
AUV_TERRAIN_MANUAL_SETPOINT="${AUV_TERRAIN_MANUAL_SETPOINT:-false}"
AUV_TERRAIN_TARGET_ALTITUDE_M="${AUV_TERRAIN_TARGET_ALTITUDE_M:-3.0}"
AUV_TERRAIN_TARGET_HEADING_DEG="${AUV_TERRAIN_TARGET_HEADING_DEG:-0.0}"
AUV_TERRAIN_TARGET_SPEED_MPS="${AUV_TERRAIN_TARGET_SPEED_MPS:-0.4}"
AUV_TERRAIN_MANUAL_RATE_HZ="${AUV_TERRAIN_MANUAL_RATE_HZ:-10.0}"
if [[ "$AUV_TERRAIN_MANUAL_SETPOINT" == "true" ]]; then
  AUV_TERRAIN_BYPASS_TO_MANUAL_SETPOINT="true"
fi

DURATION=${1:-120}
CONTROLLER_SET=${2:-both}
MODE_SET=${3:-both_modes}
TERRAIN_SET=${4:-default}
TIMESTAMP=$(date +%Y%m%d_%H%M%S)
OUTPUT_BASE="$ROOT_DIR/results/control/terrain_following_${TIMESTAMP}"
mkdir -p "$OUTPUT_BASE"

case "$CONTROLLER_SET" in
  pid) CONTROLLERS=("pid") ;;
  mpc) CONTROLLERS=("mpc") ;;
  both) CONTROLLERS=("pid" "mpc") ;;
  *)
    echo "Usage: bash scripts/run_terrain_benchmark.sh [DURATION_SECONDS] [pid|mpc|both] [baseline|terrain|both_modes] [default|low|mid|high|<bridge_cfg.yaml>]" >&2
    exit 2
    ;;
esac

case "$MODE_SET" in
  baseline) MODES=("baseline") ;;
  terrain) MODES=("terrain") ;;
  both_modes|both) MODES=("baseline" "terrain") ;;
  *)
    echo "Usage: bash scripts/run_terrain_benchmark.sh [DURATION_SECONDS] [pid|mpc|both] [baseline|terrain|both_modes]" >&2
    exit 2
    ;;
esac

if [[ -z "$TERRAIN_BRIDGE_CFG" ]]; then
  case "$TERRAIN_SET" in
    default)
      TERRAIN_BRIDGE_CFG="$DEFAULT_TERRAIN_BRIDGE_CFG"
      ;;
    low|mid|high)
      TERRAIN_BRIDGE_CFG="$ROOT_DIR/config/bridge_params.protocol_udp.pvs.terrain_${TERRAIN_SET}.yaml"
      ;;
    *.yaml|*.yml)
      if [[ "$TERRAIN_SET" = /* ]]; then
        TERRAIN_BRIDGE_CFG="$TERRAIN_SET"
      else
        TERRAIN_BRIDGE_CFG="$ROOT_DIR/$TERRAIN_SET"
      fi
      ;;
    *)
      echo "Usage: bash scripts/run_terrain_benchmark.sh [DURATION_SECONDS] [pid|mpc|both] [baseline|terrain|both_modes] [default|low|mid|high|<bridge_cfg.yaml>]" >&2
      exit 2
      ;;
  esac
fi

if [[ ! -f "$TERRAIN_BRIDGE_CFG" ]]; then
  echo "[terrain_benchmark][ERROR] bridge config not found: $TERRAIN_BRIDGE_CFG" >&2
  exit 2
fi

cleanup() {
  if [[ -f "$FEATURE_FLAGS_BACKUP" ]]; then
    cp "$FEATURE_FLAGS_BACKUP" "$FEATURE_FLAGS"
    rm -f "$FEATURE_FLAGS_BACKUP"
    echo "[terrain_benchmark] feature_flags.yaml restored."
  fi
}

kill_orphans() {
  echo "[terrain_benchmark] orphan sweep..."
  pkill -KILL -f "run_zenoh_bridge.py" >/dev/null 2>&1 || true
  pkill -KILL -f "sim_holoocean/apps/main.py" >/dev/null 2>&1 || true
  pkill -KILL -f "python3 main.py --config" >/dev/null 2>&1 || true
  pkill -KILL -f "mock_amd_server" >/dev/null 2>&1 || true
  pkill -KILL -f "ros2 launch foxglove_bridge" >/dev/null 2>&1 || true
  pkill -KILL -f "ros2 launch.*auv_stack" >/dev/null 2>&1 || true
  pkill -KILL -f "ros2 bag record" >/dev/null 2>&1 || true
  bash "$SCRIPTS_DIR/preflight_clean.sh" --quiet >/dev/null 2>&1 || true
  sleep 2
}

write_feature_flags() {
  local depth_mode="$1"   # CONSTANT or TERRAIN_FOLLOWING
  local use_mpc="$2"      # true or false
  local depth_value="${AUV_TERRAIN_TARGET_ALTITUDE_M}"
  local comment="基准深度 3.0m"
  if [[ "$depth_mode" == "TERRAIN_FOLLOWING" ]]; then
    comment="目标离底高度 3.0m"
  fi
  cat > "$FEATURE_FLAGS" <<EOF
# Auto-generated by scripts/run_terrain_benchmark.sh
/**:
  ros__parameters:
    enable_behavior_tree: ${AUV_TERRAIN_ENABLE_BEHAVIOR_TREE}
    bypass_to_manual_setpoint: ${AUV_TERRAIN_BYPASS_TO_MANUAL_SETPOINT}
    bypass_zero_effort: false
    use_mpc: ${use_mpc}
    depth_mode: '${depth_mode}'
    heading_mode: 'CONSTANT'
    # ${comment}
    constant_depth_m: ${depth_value}
    constant_heading_rad: 0.0
    passive_mode: false
EOF
}

latest_bag_after() {
  local prev="${1:-}"
  python3 - "$LOG_ROOT" "$prev" <<'PY'
import os
import sys
root = sys.argv[1]
prev = sys.argv[2] if len(sys.argv) > 2 else ""
if not os.path.isdir(root):
    sys.exit()
entries = sorted(
    d for d in os.listdir(root)
    if d.startswith("2") and os.path.isdir(os.path.join(root, d))
)
for d in reversed(entries):
    full = os.path.join(root, d)
    if full != prev:
        print(full)
        break
PY
}

latest_bag_after_time() {
  local min_ts="$1"
  python3 - "$LOG_ROOT" "$min_ts" <<'PY'
import os
import sys
root = sys.argv[1]
min_ts = float(sys.argv[2])
if not os.path.isdir(root):
    sys.exit()
candidates = []
for d in os.listdir(root):
    full = os.path.join(root, d)
    if d.startswith("2") and os.path.isdir(full):
        try:
            mtime = os.path.getmtime(full)
        except OSError:
            continue
        if mtime >= min_ts:
            candidates.append((mtime, full))
if candidates:
    print(sorted(candidates)[-1][1])
PY
}

run_phase() {
  local controller="$1"     # pid or mpc
  local mode="$2"           # baseline or terrain
  local depth_mode="CONSTANT"
  local use_mpc="false"
  if [[ "$controller" == "mpc" ]]; then
    use_mpc="true"
  fi
  if [[ "$mode" == "terrain" ]]; then
    depth_mode="TERRAIN_FOLLOWING"
  fi

  local label="${controller}_${mode}"
  local phase_dir="$OUTPUT_BASE/$label"
  mkdir -p "$phase_dir"
  local ready_topic="/auv/control/mpc_cmd"
  if [[ "$controller" == "pid" && "$mode" == "baseline" ]]; then
    ready_topic="/cmd_vel"
  fi

  echo ""
  echo "=== ${label}: controller=${controller}, depth_mode=${depth_mode}, duration=${DURATION}s ==="
  write_feature_flags "$depth_mode" "$use_mpc"

  local phase_start_ts
  phase_start_ts=$(date +%s)
  local manual_driver_pid=""
  if [[ "$mode" == "terrain" && "$AUV_TERRAIN_MANUAL_SETPOINT" == "true" ]]; then
    local driver_duration
    driver_duration=$(python3 - "$DURATION" <<'PY'
import sys
print(float(sys.argv[1]) + 20.0)
PY
)
    echo "[${label}] starting manual terrain setpoint driver"
    bash -lc "source /opt/ros/humble/setup.bash && source '$BRAIN_CONFIG_DIR/../install/setup.bash' && /usr/bin/python3 '$ROOT_DIR/tools/single_setpoint_driver.py' --duration '$driver_duration' --csv '$phase_dir/manual_setpoint.csv' --rate-hz '$AUV_TERRAIN_MANUAL_RATE_HZ' depth='$AUV_TERRAIN_TARGET_ALTITUDE_M' heading='$AUV_TERRAIN_TARGET_HEADING_DEG' speed='$AUV_TERRAIN_TARGET_SPEED_MPS'" \
      > "$phase_dir/manual_setpoint_driver.log" 2>&1 &
    manual_driver_pid="$!"
  fi
  AUV_SKIP_BRAIN_BUILD=1 SIM_DELAY_S=0 WAIT_BEFORE_RECORD_S=0 BRAIN_READY_TIMEOUT_S=30 BRAIN_READY_TOPIC="$ready_topic" \
  bash "$SCRIPTS_DIR/start_experiment.sh" \
    --sim-backend pvs \
    --bridge-backend protocol_udp \
    --bridge-cfg "$TERRAIN_BRIDGE_CFG" \
    --arbiter-profile \
    --auto-activate \
    --duration "$DURATION" \
    --record-bag \
    2>&1 | tee "$OUTPUT_BASE/${label}_log.txt" || true

  if [[ -n "$manual_driver_pid" ]]; then
    kill "$manual_driver_pid" >/dev/null 2>&1 || true
    wait "$manual_driver_pid" >/dev/null 2>&1 || true
  fi

  LATEST_BAG=$(latest_bag_after_time "$phase_start_ts")
  if [[ -n "$LATEST_BAG" && -d "$LATEST_BAG" ]]; then
    echo "$LATEST_BAG" > "$phase_dir/bag_path.txt"
    echo "[$label] bag at: $LATEST_BAG"
  else
    echo "[WARN] $label: bag not found"
  fi

  kill_orphans
}

analyze_phase() {
  local label="$1"
  local phase_dir="$2"
  local bag_path_file="$phase_dir/bag_path.txt"
  if [[ ! -f "$bag_path_file" ]]; then
    echo "[WARN] $label: bag_path.txt missing, skip"
    return
  fi
  local bag_dir
  bag_dir=$(cat "$bag_path_file")
  local mcap
  mcap=$(python3 - "$bag_dir" <<'PY'
import os
import sys
root = sys.argv[1]
for dirpath, _, files in os.walk(root):
    for f in files:
        if f.endswith(".mcap"):
            print(os.path.join(dirpath, f))
            raise SystemExit
PY
)

  local analysis_dir="$phase_dir/analysis"
  mkdir -p "$analysis_dir"

  if [[ -z "$mcap" ]]; then
    echo "[WARN] $label: no mcap under $bag_dir"
    echo "NO_MCAP" > "$analysis_dir/SKIPPED.txt"
    return
  fi
  if [[ ! -s "$mcap" ]]; then
    echo "[WARN] $label: mcap is 0 byte ($mcap)"
    {
      echo "EMPTY_BAG"
      echo "mcap=$mcap"
      echo "size=0"
    } > "$analysis_dir/SKIPPED.txt"
    return
  fi
  echo "[$label] analyzing $mcap"
  local control_mode="auto"
  case "$label" in
    *_terrain) control_mode="terrain" ;;
    *_baseline) control_mode="baseline" ;;
  esac
  python3 "$ROOT_DIR/tools/analyze_bag.py" "$mcap" \
    --output-dir "$analysis_dir" \
    --control-mode "$control_mode" \
    --warmup-skip-s "$AUV_WARMUP_SKIP_S" 2>&1 \
    || echo "[WARN] $label analysis exited non-zero"
}

trap cleanup EXIT
trap 'cleanup; exit 130' INT TERM

cp "$FEATURE_FLAGS" "$FEATURE_FLAGS_BACKUP"
LATEST_BAG="$(latest_bag_after "")"
kill_orphans

echo "═══════════════════════════════════════════════════"
echo " Terrain Following Benchmark"
echo " Duration per phase: ${DURATION}s"
echo " Controllers: ${CONTROLLERS[*]}"
echo " Modes: ${MODES[*]}"
echo " Terrain set: $TERRAIN_SET"
echo " Bridge config: $TERRAIN_BRIDGE_CFG"
echo " Output: $OUTPUT_BASE"
echo "═══════════════════════════════════════════════════"

if [[ "${AUV_BENCHMARK_SKIP_PREBUILD:-0}" == "1" ]]; then
  echo "[terrain_benchmark] skipping prebuild because AUV_BENCHMARK_SKIP_PREBUILD=1"
else
  echo "[terrain_benchmark] prebuilding brain stack once before timed phases..."
  bash "$SCRIPTS_DIR/start_lin_brain.sh" bootstrap
fi

for controller in "${CONTROLLERS[@]}"; do
  for mode in "${MODES[@]}"; do
    run_phase "$controller" "$mode"
  done
done

cp "$FEATURE_FLAGS_BACKUP" "$FEATURE_FLAGS"
rm -f "$FEATURE_FLAGS_BACKUP"

echo ""
echo "=== Analysis ==="
for controller in "${CONTROLLERS[@]}"; do
  for mode in "${MODES[@]}"; do
    analyze_phase "${controller}_${mode}" "$OUTPUT_BASE/${controller}_${mode}"
  done
done

echo ""
echo "═══════════════════════════════════════════════════"
echo " Benchmark complete!"
echo " Results: $OUTPUT_BASE"
echo ""
echo " Key metrics to compare:"
echo "   - seabed_clearance_mean_m (terrain mode should be ~3.0m)"
echo "   - seabed_clearance_min_m  (safety: should be > 1.5m)"
echo "   - depth_error_rmse_m      (tracking accuracy)"
echo "═══════════════════════════════════════════════════"
